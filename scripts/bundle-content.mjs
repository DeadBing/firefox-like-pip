import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const sources = [
  "lib/settings.js",
  "lib/format.js",
  "lib/captions.js",
  "lib/video-utils.js",
  "lib/keys.js",
  "pip/player.js",
  "content/content.js",
];

function stripModuleSyntax(source, file) {
  let next = source.replace(/import\s+(?:type\s+)?(?:[\s\S]*?)\s+from\s+["'][^"']+["'];?\s*/g, "");
  next = next.replace(/^export\s+\{[^}]*\}\s*;?\s*/gm, "");
  next = next.replace(/^export\s+default\s+/gm, "");
  next = next.replace(/^export\s+/gm, "");
  if (/\bimport\s+|^\s*export\s+/m.test(next)) {
    throw new Error(`Could not fully strip module syntax from ${file}`);
  }
  return next.trim();
}

const body = sources
  .map((file) => {
    const raw = readFileSync(join(root, file), "utf8");
    return `/* ---- ${file} ---- */\n${stripModuleSyntax(raw, file)}`;
  })
  .join("\n\n");

const banner = `/* Generated by scripts/bundle-content.mjs. Do not edit. */\n`;
const output = `${banner}"use strict";\n(() => {\n${body}\n})();\n`;
const dest = join(root, "content/injected.js");
writeFileSync(dest, output);
console.log(`Wrote ${dest} (${output.length} bytes)`);
